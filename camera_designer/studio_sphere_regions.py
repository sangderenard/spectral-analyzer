"""Exact saved spherical boundaries in the existing Studio photo renderer.

The intersection shader is generated by the original SphericalSurface kernel.
An analytic hit retains one existing TriGeom/TriShade owner for materials and
explicit media, but its triangle is degenerate and never enters geometric
transport. All other authored triangles remain unchanged.
"""
from __future__ import annotations

import numpy as np
from .parametric_surfaces import SphericalSurface


STUDIO_SPHERE_GLSL = r'''
struct StudioSphereRegion { vec4 center_radius; vec4 owner; };
// 11 is reserved for the existing Auto bounce diagnostic.
layout(std430,binding=12) readonly buffer StudioSphereBuf { StudioSphereRegion studio_spheres[]; };
uniform int uStudioSphereCount;
''' + SphericalSurface(R=1.0, r_max=1.0).glsl_intercept_fn(
    "studio_original_unit_sphere", min_t_argument=True) + r'''

bool studio_sphere_hit(int si, vec3 ro, vec3 rd, out float t) {
    vec4 sphere=studio_spheres[si].center_radius;
    float ray_length=length(rd);
    if(ray_length<=0.0 || sphere.w<=0.0) return false;
    // Original kernel: sphere center=(0,0,R), here R=1. Transform the
    // complete region, not a hit triangle. Both roots and the full silhouette
    // participate in nearest-hit selection before any material processing.
    vec3 local_origin=(ro-sphere.xyz)/sphere.w+vec3(0.0,0.0,1.0);
    float local_t; vec3 unused_normal;
    if(!studio_original_unit_sphere(local_origin,rd/ray_length,
        1e-6*ray_length/sphere.w,local_t,unused_normal)) return false;
    t=local_t*sphere.w/ray_length;
    return true;
}

Tri studio_hit_tri(int ti,vec3 position) {
    Tri t=load_tri(ti);
    for(int si=0;si<uStudioSphereCount;++si) {
        if(int(studio_spheres[si].owner.x)==ti) {
            t.normal.xyz=normalize(position-studio_spheres[si].center_radius.xyz);
            break;
        }
    }
    return t;
}
'''


def validate_sphere_regions(value, vertices, material_ids, pbr):
    """Check authenticated metadata against the verified saved mesh.

    This validates descriptors; it never discovers ownership by material ID.
    The caller obtains descriptors from the immutable saved design, not the
    exposure request. Float32 mesh quantization allows a bounded radial error.
    """
    if not isinstance(value, dict) or set(value) != {"version", "spheres"} or value["version"] != 1:
        raise ValueError("Exact spheres require saved version 1 analytic sphere metadata")
    spheres = value["spheres"]
    if not isinstance(spheres, list) or not 1 <= len(spheres) <= 65:
        raise ValueError("Exact spheres require between 1 and 65 saved spheres")
    verts = np.asarray(vertices, np.float64)
    ids = np.asarray(material_ids, np.int64)
    rows = np.asarray(pbr, np.float64)
    occupied = np.zeros(len(verts), bool)
    result = []
    for sphere in spheres:
        if not isinstance(sphere, dict) or set(sphere) != {"start", "count", "center", "radius"}:
            raise ValueError("Invalid analytic sphere descriptor")
        start, count = sphere["start"], sphere["count"]
        if any(isinstance(v, bool) or not isinstance(v, int) for v in (start, count)) or start < 0 or count < 4 or start + count > len(verts):
            raise ValueError("Analytic sphere membership is outside the saved mesh")
        if np.any(occupied[start:start + count]):
            raise ValueError("Analytic sphere memberships overlap")
        occupied[start:start + count] = True
        center = np.asarray(sphere["center"], np.float64)
        radius = sphere["radius"]
        if center.shape != (3,) or not np.isfinite(center).all() or isinstance(radius, bool) or not isinstance(radius, (int, float)) or not np.isfinite(radius) or not 0 < radius <= 1:
            raise ValueError("Analytic sphere center/radius must be finite radius-unit coordinates")
        if np.linalg.norm(center) + radius > 1.000003:
            raise ValueError("Analytic sphere lies outside the saved marble")
        face_ids = ids[start:start + count]
        if not np.all(face_ids == face_ids[0]):
            raise ValueError("Exact spheres require uniform material on each saved spherical boundary")
        row = rows[int(face_ids[0])]
        if np.any(row[8:11] != 0):
            raise ValueError("Exact emissive spheres are not supported by the area-source sampler")
        tri = verts[start:start + count]
        radii = np.linalg.norm(tri - center, axis=2)
        if not np.allclose(radii, radius, rtol=0, atol=3e-6):
            raise ValueError("Saved triangles do not match their analytic spherical boundary")
        cross = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
        nonzero = np.linalg.norm(cross, axis=1) > 1e-12
        if not np.any(nonzero) or np.any(np.einsum("ij,ij->i", cross[nonzero], tri[nonzero, 0] - center) <= 0):
            raise ValueError("Analytic sphere requires outward-wound nondegenerate saved faces")
        result.append({"start": start, "count": count, "center": center.tolist(), "radius": float(radius)})
    return {"version": 1, "spheres": result}


def with_sphere_regions(source):
    """Extend both canonical shader programs at the same geometry seam.

    Assertions make a changed original contract fail loudly, not silently
    leave one direction on faceted geometry. Physics remains in its existing
    material/medium branches.
    """
    marker = "bool studio_media_enabled()"
    if source.count(marker) != 1 or source.count("    int stack[96];") != 1:
        raise RuntimeError("Canonical Studio geometry seam changed; exact sphere integration needs review")
    source = source.replace(marker, STUDIO_SPHERE_GLSL + "\n" + marker, 1)
    source = source.replace("Tri b=load_tri(hit);", "Tri b=studio_hit_tri(hit,ro+rd*t);", 1)
    source = source.replace("= load_tri(hit);", "= studio_hit_tri(hit,hp);")
    source = source.replace("= load_tri(hit_id);", "= studio_hit_tri(hit_id,hp);")
    source = source.replace("    int stack[96];", """    // Analytic regions compete with every ordinary triangle. Their owner
    // record has degenerate geometry, so the shell cannot double-intersect.
    for(int si=0;si<uStudioSphereCount;++si) {
        int ti=int(studio_spheres[si].owner.x);
        if(boundary_only && !(geom_tris[ti].v0.w>=1.0 && shade_tris[ti].mat_out.w<0.999)) continue;
        float ht;
        if(studio_sphere_hit(si,ro,rd,ht) && ht<best) {best=ht;best_tri=ti;}
    }
    int stack[96];""", 1)
    return source


def pack_sphere_regions(scene, original_indices, object_offset, regions, *, scale_m, center_m,
                        response_lineage_out=None):
    """Replace only declared sphere faces, retaining owner materials/media."""
    geom, shade, mat, tris, contexts, ctx_map, bounds, sources = scene
    indices = np.asarray(original_indices, np.int64)
    keep = np.ones(len(geom), bool)
    spheres = regions["spheres"]
    records = np.zeros((len(spheres), 8), np.float32)
    representatives = []
    for i, sphere in enumerate(spheres):
        selected = np.flatnonzero((indices >= sphere["start"]) & (indices < sphere["start"] + sphere["count"])) + int(object_offset)
        if not len(selected):
            raise ValueError("Analytic sphere has no retained material owner after triangle filtering")
        representative = int(selected[0])
        # Material and boundary-side equality are essential: the representative
        # cannot erase an authored coating or a change of medium.
        if not np.all(shade[selected] == shade[representative]) or not np.all(geom[selected][:, [3, 7]] == geom[representative, [3, 7]]):
            raise ValueError("Analytic sphere spans distinct materials or medium pairs")
        keep[selected] = False
        keep[representative] = True
        representatives.append(representative)
        records[i, :3] = np.asarray(center_m, np.float64) + float(scale_m) * np.asarray(sphere["center"])
        records[i, 3] = float(scale_m) * sphere["radius"]
    old_to_new = np.cumsum(keep, dtype=np.int64) - 1
    if response_lineage_out is not None:
        response_lineage_out.compact_spheres(keep, old_to_new, representatives, spheres)
    geom, shade, tris = geom[keep].copy(), shade[keep].copy(), tris[keep].copy()
    for i, old in enumerate(representatives):
        index = int(old_to_new[old])
        records[i, 4] = index
        geom[index, :3] = records[i, :3]
        geom[index, 4:7] = 0
        geom[index, 8:11] = 0
        tris[index] = records[i, :3]
    lower = np.minimum(bounds[0], np.min(records[:, :3] - records[:, 3, None], axis=0))
    upper = np.maximum(bounds[1], np.max(records[:, :3] + records[:, 3, None], axis=0))
    return (geom, shade, mat, tris, contexts, ctx_map, (lower, upper), sources), records


def geometry_statistics(*, input_triangles, packed_triangles, sphere_count, policy, budget):
    if policy not in ("mesh", "exact"):
        raise ValueError("sphere_coverage must be mesh or exact")
    if isinstance(budget, bool) or not isinstance(budget, int) or not 1000 <= budget <= 1000000:
        raise ValueError("triangle_budget must be an integer from 1000 to 1000000")
    effective = int(packed_triangles) - int(sphere_count)
    if effective > budget:
        raise ValueError(f"Scene needs {effective} triangles; exposure budget is {budget}. Raise the budget or simplify the saved design.")
    return {"sphere_coverage": policy, "triangle_budget": budget,
            "input_triangles": int(input_triangles), "effective_triangles": effective,
            "analytic_spheres": int(sphere_count)}
